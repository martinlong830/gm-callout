const DICTS: Record<Locale, Dict> = { en: EN, es: ES };

export function isLocale(value: unknown): value is Locale {
  return value === 'en' || value === 'es';
}

export function translate(locale: Locale, key: string, vars?: Record<string, string | number>): string {
  const raw = DICTS[locale][key] ?? DICTS.en[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (_, name: string) =>
    vars[name] != null ? String(vars[name]) : `{${name}}`
  );
}

export function staffTypeLabel(locale: Locale, code: string | null | undefined): string {
  if (code === 'Kitchen') return translate(locale, 'staff.kitchen');
  if (code === 'Bartender') return translate(locale, 'staff.bartender');
  if (code === 'Server') return translate(locale, 'staff.server');
  return code || translate(locale, 'staff.staff');
}

export function statusLabel(locale: Locale, status: string | null | undefined): string {
  const s = String(status || '').toLowerCase();
  if (s === 'approved') return translate(locale, 'status.approved');
  if (s === 'declined') return translate(locale, 'status.declined');
  if (s === 'awaiting_cover') return translate(locale, 'status.awaiting_cover');
  if (s === 'pending_approval') return translate(locale, 'status.pending_approval');
  if (s === 'pending') return translate(locale, 'status.pending');
  if (s === 'draft') return translate(locale, 'status.draft');
  return status || '';
}

export function dateLocaleTag(locale: Locale): string {
  return locale === 'es' ? 'es' : 'en-US';
}
